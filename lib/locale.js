export function translate(locale, text) {
  if (locale !== "km" || typeof text !== "string") {
    return text;
  }
  if (KHMER_MESSAGES[text]) {
    return KHMER_MESSAGES[text];
  }

  const patterns = [
    [/^Enter a username of up to (\d+) characters\.$/u, (_, max) => `បញ្ចូលឈ្មោះអ្នកប្រើដែលមានប្រវែងមិនលើស ${max} តួអក្សរ។`],
    [/^Password must be at least (\d+) characters$/u, (_, min) => `ពាក្យសម្ងាត់ត្រូវមានយ៉ាងតិច ${min} តួអក្សរ។`],
    [/^Password must be (\d+) characters or fewer$/u, (_, max) => `ពាក្យសម្ងាត់មិនអាចលើស ${max} តួអក្សរទេ។`],
    [/^Enter a title between (\d+) and (\d+) characters\.$/u, (_, min, max) => `បញ្ចូលចំណងជើងដែលមានប្រវែងពី ${min} ដល់ ${max} តួអក្សរ។`],
    [/^Enter a Khmer title \(up to (\d+) characters\)\.$/u, (_, max) => `បញ្ចូលចំណងជើងជាភាសាខ្មែរ ដែលមានប្រវែងមិនលើស ${max} តួអក្សរ។`],
    [/^Summary must be no longer than (\d+) characters\.$/u, (_, max) => `សេចក្ដីសង្ខេបមិនអាចលើស ${max} តួអក្សរទេ។`],
    [/^Enter a description between (\d+) and (\d+) characters\.$/u, (_, min, max) => `បញ្ចូលសេចក្ដីពិពណ៌នាដែលមានប្រវែងពី ${min} ដល់ ${max} តួអក្សរ។`],
    [/^Location must be (\d+) to (\d+) characters\.$/u, (_, min, max) => `ទីតាំងត្រូវមានប្រវែងពី ${min} ដល់ ${max} តួអក្សរ។`],
    [/^Maximum of (\d+) characters reached\.$/u, (_, max) => `អ្នកបានឈានដល់ចំនួនអតិបរមា ${max} តួអក្សរ។`],
  ];

  for (const [pattern, render] of patterns) {
    const match = text.match(pattern);
    if (match) return text.replace(pattern, render);
  }
  return text;
}

export function getLocalizedTitles(locale, englishTitle, khmerTitle) {
  const hasKhmerTitle = typeof khmerTitle === "string" && khmerTitle.trim().length > 0;
  const showKhmerAsPrimary = locale === "km" && hasKhmerTitle;
  const primaryTitle = showKhmerAsPrimary ? khmerTitle : englishTitle ?? "";
  const alternateTitle = showKhmerAsPrimary ? englishTitle : khmerTitle;

  return {
    primaryTitle,
    alternateTitle: typeof alternateTitle === "string" ? alternateTitle : "",
    primaryLocale: showKhmerAsPrimary ? "km" : "en",
    alternateLocale: showKhmerAsPrimary ? "en" : "km",
    showKhmerAsPrimary,
  };
}

